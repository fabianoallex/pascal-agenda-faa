#!/bin/sh
# Customers and users over HTTP, sourced by tools/http_scenarios.sh after
# tools/http_scenarios_catalog.sh (it uses that file's helpers, $OWNER,
# $STAFF, $OTHER, and the professional $ANA it left).
#
# Logins here count against the /auth/ rate limit the main script checks
# last (60 a minute per address): keep them few (7 today).

# --- customers: any user creates and changes
req POST /customers '{"name":"Maria Lima","phone":"+55 (11) 99999-0000","email":" Maria@Example.Test "}' -H "$STAFF"
status_is 201 "customers: staff creates"
body_has '"name":"Maria Lima","phone":"+5511999990000","email":"maria@example.test"' "customers: phone and email normalized"
MARIA="$(id_of)"
printf '{"name":"Jos\303\251 Ara\303\272jo"}' > "$T/in.json"
post_file /customers "$OWNER"
status_is 201 "customers: create without contacts"
body_has '"phone":null,"email":null' "customers: no contacts are null"
JOSE="$(id_of)"
req POST /customers '{"name":"Maria Lima","phone":"11 3333-4444"}' -H "$OWNER"
status_is 201 "customers: names and contacts may repeat"
TWIN="$(id_of)"

req POST /customers '{"name":"X","phone":"call me"}' -H "$STAFF"
status_is 400 "customers: a phone with letters"
body_has 'phone' "customers: the phone, named"
req POST /customers '{"name":"X","phone":"123-456"}' -H "$STAFF"
status_is 400 "customers: a phone too short"
req POST /customers '{"name":"X","email":"nope"}' -H "$STAFF"
status_is 400 "customers: an invalid email"
req POST /customers '{"name":"  "}' -H "$STAFF"
body_is '{"error":"\"name\" is required.","code":"name_required"}' "customers: a blank name, its code"
req POST /customers '{"name":"X","cpf":"1"}' -H "$STAFF"
status_is 400 "customers: an unknown member"

# Listing and the search: name (case, accents), email, phone (its digits)
req GET /customers "" -H "$STAFF"
status_is 200 "customers: staff lists"
body_has '"total":3,' "customers: three"
body_has "\"items\":[{\"id\":\"$JOSE\"" "customers: by name, by default"
req GET "/customers?search=ARAUJO" "" -H "$STAFF"
body_has '"total":1,' "customers: search ignores case and accents"
req GET "/customers?search=maria@exa" "" -H "$STAFF"
body_has '"total":1,' "customers: search in the email"
body_has "\"id\":\"$MARIA\"" "customers: found by the email"
req GET "/customers?search=(11)%2099999" "" -H "$STAFF"
body_has '"total":1,' "customers: a phone typed with punctuation"
body_has "\"id\":\"$MARIA\"" "customers: found by the phone"
req GET "/customers?search=3333" "" -H "$STAFF"
body_has '"total":1,' "customers: search by part of a phone"
body_has "\"id\":\"$TWIN\"" "customers: found by part of the phone"
req GET "/customers?search=maria%20lima" "" -H "$STAFF"
body_has '"total":2,' "customers: two with the same name"
req GET "/customers?search=%25" "" -H "$STAFF"
body_has '"total":0,' "customers: a % is literal"
# Created in the same second: only the ordering's acceptance is checked.
req GET "/customers?orderBy=-createdAt&limit=1" "" -H "$STAFF"
body_has '"limit":1,"total":3,' "customers: by creation, a page of one"
req GET "/customers?orderBy=phone" "" -H "$STAFF"
status_is 400 "customers: an order field not allowed"
req GET "/customers/$MARIA" "" -H "$STAFF"
status_is 200 "customers: one"
req GET "/customers/nothing" "" -H "$STAFF"
status_is 404 "customers: an unknown id"

# Changing: absent keeps, null clears, and the search key follows
req PATCH "/customers/$MARIA" '{"phone":null}' -H "$STAFF"
status_is 200 "customers: staff patches"
body_has '"name":"Maria Lima","phone":null,"email":"maria@example.test"' "customers: null clears the phone, the email stays"
req GET "/customers?search=99999" "" -H "$STAFF"
body_has '"total":0,' "customers: the old phone no longer found"
printf '{"name":"Maria Lima Concei\303\247\303\243o","phone":"21 98888-7777"}' > "$T/in.json"
patch_file "/customers/$MARIA" "$STAFF"
body_has '"phone":"21988887777","email":"maria@example.test"' "customers: a new phone"
req GET "/customers?search=conceicao" "" -H "$STAFF"
body_has "\"id\":\"$MARIA\"" "customers: found by the new name"
req GET "/customers?search=98888" "" -H "$STAFF"
body_has "\"id\":\"$MARIA\"" "customers: found by the new phone"
req PATCH "/customers/$MARIA" '{"phone":"x"}' -H "$STAFF"
status_is 400 "customers: patch an invalid phone"
req PATCH "/customers/$MARIA" '{"name":null}' -H "$STAFF"
status_is 400 "customers: the name can't be null"
req PATCH "/customers/nothing" '{"phone":null}' -H "$STAFF"
status_is 404 "customers: patch an unknown id"

# Another tenant sees nothing of demo's
req GET /customers "" -H "$OTHER"
body_has '"total":0,' "customers: other tenant's list is its own"
req GET "/customers/$MARIA" "" -H "$OTHER"
status_is 404 "customers: other tenant can't read demo's"
req PATCH "/customers/$MARIA" '{"phone":null}' -H "$OTHER"
status_is 404 "customers: other tenant can't change demo's"
req DELETE "/customers/$MARIA" "" -H "$OTHER"
status_is 404 "customers: other tenant can't delete demo's"

# Deleting: the owner only
req DELETE "/customers/$TWIN" "" -H "$STAFF"
status_is 403 "customers: staff can't delete"
req DELETE "/customers/$TWIN" "" -H "$OWNER"
status_is 204 "customers: delete"
req DELETE "/customers/$TWIN" "" -H "$OWNER"
status_is 404 "customers: delete again"

# --- users: the owner only
req GET /me "" -H "$OWNER"
SELF="$(id_of)"
req GET /users "" -H "$STAFF"
status_is 403 "users: staff can't list"
req POST /users '{"email":"x@demo.test","password":"long enough","role":"staff"}' -H "$STAFF"
status_is 403 "users: staff can't create"

req GET /users "" -H "$OWNER"
status_is 200 "users: list"
body_has '"total":2,' "users: owner and staff"
body_has "\"items\":[{\"id\":\"$SELF\",\"email\":\"owner@demo.test\",\"role\":\"owner\",\"active\":true,\"professionalId\":null}" "users: by email, the owner first"
body_lacks 'password' "users: no password or hash in the list"

req POST /users "{\"email\":\" Ana@Demo.Test \",\"password\":\"ana's passphrase\",\"role\":\"staff\",\"professionalId\":\"$ANA\"}" -H "$OWNER"
status_is 201 "users: create, linked to a professional"
body_has "\"email\":\"ana@demo.test\",\"role\":\"staff\",\"active\":true,\"professionalId\":\"$ANA\"" "users: the stored values"
body_lacks 'password' "users: the password is not returned"
NEWU="$(id_of)"
login demo ana@demo.test "ana's passphrase"
status_is 200 "users: the new user logs in"
NEW_REFRESH="$(field refreshToken)"

req POST /users '{"email":"ANA@demo.test","password":"long enough","role":"staff"}' -H "$OWNER"
status_is 409 "users: an email the tenant has (other case)"
req POST /users "{\"email\":\"bia@demo.test\",\"password\":\"long enough\",\"role\":\"staff\",\"professionalId\":\"$ANA\"}" -H "$OWNER"
status_is 409 "users: a professional another user is"
req POST /users '{"email":"bia@demo.test","password":"long enough","role":"staff","professionalId":"nothing"}' -H "$OWNER"
status_is 400 "users: an unknown professional"
body_has '"code":"unknown_professional"' "users: an unknown professional, its code"
req POST /users '{"email":"bia@demo.test","password":"short","role":"staff"}' -H "$OWNER"
status_is 400 "users: a short password"
body_has '"code":"password_too_short"' "users: a short password, its code"
req POST /users '{"email":"bia@demo.test","password":"long enough","role":"boss"}' -H "$OWNER"
status_is 400 "users: a role that doesn't exist"
req POST /users '{"email":"bia","password":"long enough","role":"staff"}' -H "$OWNER"
status_is 400 "users: an invalid email"
req POST /users '{"email":"bia@demo.test","role":"staff"}' -H "$OWNER"
status_is 400 "users: no password"

req GET "/users?role=staff" "" -H "$OWNER"
body_has '"total":2,' "users: by role"
req GET "/users?search=ana&role=staff" "" -H "$OWNER"
status_is 200 "users: search and role together (500 before ESCAPE '!')"
body_has '"total":1,' "users: search and role together, the right row"
req GET "/users?role=boss" "" -H "$OWNER"
status_is 400 "users: an unknown role in the filter"
req GET "/users?search=ANA@" "" -H "$OWNER"
body_has '"total":1,' "users: search in the email"
req GET "/users?orderBy=-createdAt&limit=1" "" -H "$OWNER"
body_has "\"items\":[{\"id\":\"$NEWU\"" "users: the newest first"
req GET "/users/$NEWU" "" -H "$OWNER"
status_is 200 "users: one"

# The owner can't lock themselves out
req PATCH "/users/$SELF" '{"role":"staff"}' -H "$OWNER"
status_is 409 "users: not your own role"
body_has '"code":"own_account"' "users: own_account"
req PATCH "/users/$SELF" '{"active":false}' -H "$OWNER"
status_is 409 "users: not deactivate yourself"
req DELETE "/users/$SELF" "" -H "$OWNER"
status_is 409 "users: not delete yourself"
req PATCH "/users/$SELF" '{"role":"owner"}' -H "$OWNER"
status_is 200 "users: keeping your own role is fine"

# A new password ends the sessions
req PATCH "/users/$NEWU" '{"password":"a brand new one"}' -H "$OWNER"
status_is 200 "users: a new password"
refresh "$NEW_REFRESH"
status_is 401 "users: the refresh token from before the new password"
login demo ana@demo.test "ana's passphrase"
status_is 401 "users: the old password"
login demo ana@demo.test "a brand new one"
status_is 200 "users: the new password"

# Email, role, active, the professional link
req PATCH "/users/$NEWU" '{"email":"owner@demo.test"}' -H "$OWNER"
status_is 409 "users: another user's email"
req PATCH "/users/$NEWU" '{"role":"owner","professionalId":null}' -H "$OWNER"
body_has '"role":"owner","active":true,"professionalId":null' "users: promoted, unlinked"
req PATCH "/users/$NEWU" "{\"role\":\"staff\",\"professionalId\":\"$ANA\"}" -H "$OWNER"
body_has "\"role\":\"staff\",\"active\":true,\"professionalId\":\"$ANA\"" "users: linked again"
req PATCH "/users/$NEWU" '{"active":false}' -H "$OWNER"
body_has '"active":false' "users: deactivated"
login demo ana@demo.test "a brand new one"
status_is 401 "users: a deactivated user can't log in"
req GET "/users?active=false" "" -H "$OWNER"
body_has '"total":1,' "users: only the inactive"
req PATCH "/users/nothing" '{"active":true}' -H "$OWNER"
status_is 404 "users: patch an unknown id"

# Deleting the professional unlinks the user
req DELETE "/professionals/$ANA" "" -H "$OWNER"
status_is 204 "users: the linked professional deleted"
req GET "/users/$NEWU" "" -H "$OWNER"
body_has '"professionalId":null' "users: unlinked by the delete"

# Another tenant sees nothing of demo's
req GET "/users/$NEWU" "" -H "$OTHER"
status_is 404 "users: other tenant can't read demo's"
req PATCH "/users/$NEWU" '{"active":true}' -H "$OTHER"
status_is 404 "users: other tenant can't change demo's"
req DELETE "/users/$NEWU" "" -H "$OTHER"
status_is 404 "users: other tenant can't delete demo's"

# Deleting a user who has refresh tokens
req DELETE "/users/$NEWU" "" -H "$OWNER"
status_is 204 "users: delete"
req GET "/users/$NEWU" "" -H "$OWNER"
status_is 404 "users: deleted"
req POST /users '{"email":"ana@demo.test","password":"long enough","role":"staff"}' -H "$OWNER"
status_is 201 "users: the email is free again"
