#!/bin/sh
# Working hours and time off over HTTP, sourced by tools/http_scenarios.sh
# after tools/http_scenarios_people.sh (it uses the catalog file's helpers,
# $OWNER, $STAFF and $OTHER). No logins here.

req POST /professionals '{"name":"Carla Dias"}' -H "$OWNER"
status_is 201 "schedule: a professional"
PRO="$(id_of)"
req POST /professionals '{"name":"Davi Reis"}' -H "$OWNER"
PRO2="$(id_of)"

# --- working hours: read whole, replaced whole
req GET "/professionals/$PRO/working-hours" "" -H "$STAFF"
status_is 200 "hours: staff reads"
body_is '{"intervals":[]}' "hours: none at first"

WEEK='{"intervals":[{"weekday":2,"from":"14:00","to":"18:00"},{"weekday":1,"from":"12:00","to":"24:00"},{"weekday":1,"from":"09:00","to":"12:00"},{"weekday":7,"from":"00:00","to":"06:30"}]}'
req PUT "/professionals/$PRO/working-hours" "$WEEK" -H "$STAFF"
status_is 403 "hours: staff can't change"
req PUT "/professionals/$PRO/working-hours" "$WEEK" -H "$OWNER"
status_is 200 "hours: replace the week"
SORTED='{"intervals":[{"weekday":1,"from":"09:00","to":"12:00"},{"weekday":1,"from":"12:00","to":"24:00"},{"weekday":2,"from":"14:00","to":"18:00"},{"weekday":7,"from":"00:00","to":"06:30"}]}'
body_is "$SORTED" "hours: sorted, touching intervals kept, 24:00"
req GET "/professionals/$PRO/working-hours" "" -H "$STAFF"
body_is "$SORTED" "hours: as stored"

# A refused week changes nothing
req PUT "/professionals/$PRO/working-hours" '{"intervals":[{"weekday":3,"from":"09:00","to":"12:00"},{"weekday":3,"from":"11:30","to":"13:00"}]}' -H "$OWNER"
status_is 400 "hours: an overlap"
body_is '{"error":"Weekday 3: 09:00-12:00 overlaps 11:30-13:00.","code":"invalid_week"}' "hours: the overlap, named"
req GET "/professionals/$PRO/working-hours" "" -H "$STAFF"
body_is "$SORTED" "hours: unchanged after a refusal"
req PUT "/professionals/$PRO/working-hours" '{"intervals":[{"weekday":8,"from":"09:00","to":"12:00"}]}' -H "$OWNER"
status_is 400 "hours: weekday 8"
body_has 'intervals[0]: \"weekday\"' "hours: the weekday, with its index"
req PUT "/professionals/$PRO/working-hours" '{"intervals":[{"weekday":1,"from":"08:00","to":"09:00"},{"weekday":1,"from":"9:00","to":"12:00"}]}' -H "$OWNER"
status_is 400 "hours: a time not HH:MM"
body_has 'intervals[1]: \"from\" must be HH:MM' "hours: the time, with its index"
req PUT "/professionals/$PRO/working-hours" '{"intervals":[{"weekday":1,"from":"09:03","to":"12:00"}]}' -H "$OWNER"
status_is 400 "hours: not a multiple of 5 minutes"
req PUT "/professionals/$PRO/working-hours" '{"intervals":[{"weekday":1,"from":"18:00","to":"09:00"}]}' -H "$OWNER"
status_is 400 "hours: from after to"
req PUT "/professionals/$PRO/working-hours" '{"intervals":[{"weekday":1,"from":"09:00","to":"24:30"}]}' -H "$OWNER"
status_is 400 "hours: past midnight"
req PUT "/professionals/$PRO/working-hours" '{"intervals":[null]}' -H "$OWNER"
status_is 400 "hours: a null interval"
req PUT "/professionals/$PRO/working-hours" '{"intervals":[{"weekday":1,"from":"09:00","to":"12:00","until":"x"}]}' -H "$OWNER"
status_is 400 "hours: an unknown member"
req GET "/professionals/$PRO/working-hours" "" -H "$STAFF"
body_is "$SORTED" "hours: still unchanged"

req PUT "/professionals/$PRO2/working-hours" '{"intervals":[{"weekday":5,"from":"10:00","to":"16:00"}]}' -H "$OWNER"
status_is 200 "hours: another professional's week"
req GET "/professionals/$PRO/working-hours" "" -H "$STAFF"
body_is "$SORTED" "hours: each professional has their own"
req PUT "/professionals/$PRO2/working-hours" '{"intervals":[]}' -H "$OWNER"
body_is '{"intervals":[]}' "hours: [] clears the week"

req GET "/professionals/nothing/working-hours" "" -H "$STAFF"
status_is 404 "hours: an unknown professional"
req PUT "/professionals/nothing/working-hours" '{"intervals":[]}' -H "$OWNER"
status_is 404 "hours: replace for an unknown professional"
req GET "/professionals/$PRO/working-hours" "" -H "$OTHER"
status_is 404 "hours: other tenant can't read demo's"
req PUT "/professionals/$PRO/working-hours" '{"intervals":[]}' -H "$OTHER"
status_is 404 "hours: other tenant can't change demo's"

# --- time off: instants with their zone, back in UTC
req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-12-24T13:00:00-03:00","endsAt":"2026-12-26T09:00:00-03:00","reason":" Christmas "}' -H "$OWNER"
status_is 201 "time off: create, with an offset"
body_has '"startsAt":"2026-12-24T16:00:00Z","endsAt":"2026-12-26T12:00:00Z","reason":"Christmas"' "time off: back in UTC, the reason trimmed"
XMAS="$(id_of)"
req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-11-10T14:00Z","endsAt":"2026-11-10T15:30Z"}' -H "$OWNER"
status_is 201 "time off: create, UTC, no seconds"
body_has '"startsAt":"2026-11-10T14:00:00Z","endsAt":"2026-11-10T15:30:00Z","reason":null' "time off: no reason is null"
DOCTOR="$(id_of)"
req POST "/professionals/$PRO/time-off" '{"startsAt":"2027-01-05T00:00:00Z","endsAt":"2027-01-20T00:00:00Z","reason":"Vacation"}' -H "$OWNER"
status_is 201 "time off: a third"
VACATION="$(id_of)"
req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-11-10T15:00Z","endsAt":"2026-11-10T16:00Z"}' -H "$OWNER"
status_is 201 "time off: overlapping entries are allowed"
OVERLAP="$(id_of)"

req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-11-10T14:00:00","endsAt":"2026-11-10T15:00:00Z"}' -H "$OWNER"
status_is 400 "time off: an instant without its zone"
body_has '"code":"invalid_instant"' "time off: invalid_instant"
body_has 'startsAt' "time off: the member, named"
req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-11-10","endsAt":"2026-11-11"}' -H "$OWNER"
status_is 400 "time off: dates only"
req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-11-10T14:00:30Z","endsAt":"2026-11-10T15:00:00Z"}' -H "$OWNER"
status_is 400 "time off: seconds"
req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-11-10T15:00Z","endsAt":"2026-11-10T15:00Z"}' -H "$OWNER"
status_is 400 "time off: start equal to end"
req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-01-01T00:00Z","endsAt":"2027-01-03T00:00Z"}' -H "$OWNER"
status_is 400 "time off: longer than 366 days"
req POST "/professionals/$PRO/time-off" "{\"startsAt\":\"2026-11-10T14:00Z\",\"endsAt\":\"2026-11-10T15:00Z\",\"reason\":\"$(printf '%0201d' 0)\"}" -H "$OWNER"
status_is 400 "time off: a reason of 201 characters"
req POST "/professionals/$PRO/time-off" '{"startsAt":"2026-11-10T14:00Z","endsAt":"2026-11-10T15:00Z"}' -H "$STAFF"
status_is 403 "time off: staff can't create"
req POST "/professionals/nothing/time-off" '{"startsAt":"2026-11-10T14:00Z","endsAt":"2026-11-10T15:00Z"}' -H "$OWNER"
status_is 404 "time off: an unknown professional"

# Listing: by start, filtered by the span it overlaps
req GET "/professionals/$PRO/time-off" "" -H "$STAFF"
status_is 200 "time off: staff lists"
body_has '"total":4,' "time off: four"
body_has "\"items\":[{\"id\":\"$DOCTOR\"" "time off: the earliest first"
req GET "/professionals/$PRO/time-off?from=2026-12-01T00:00Z&to=2027-01-06T00:00Z" "" -H "$STAFF"
body_has '"total":2,' "time off: overlapping from/to"
body_has "\"items\":[{\"id\":\"$XMAS\"" "time off: christmas, then"
body_has "\"id\":\"$VACATION\"" "time off: the vacation that starts inside"
req GET "/professionals/$PRO/time-off?to=2026-11-10T15:00Z" "" -H "$STAFF"
body_has '"total":1,' "time off: to is exclusive (an entry starting at it is out)"
req GET "/professionals/$PRO/time-off?from=2027-01-20T00:00Z" "" -H "$STAFF"
body_has '"total":0,' "time off: from is exclusive of an entry ending at it"
req GET "/professionals/$PRO/time-off?orderBy=-startsAt&limit=1" "" -H "$STAFF"
body_has "\"limit\":1,\"total\":4," "time off: a page of one"
body_has "\"items\":[{\"id\":\"$VACATION\"" "time off: the latest first"
req GET "/professionals/$PRO/time-off?from=yesterday" "" -H "$STAFF"
status_is 400 "time off: from not an instant"
req GET "/professionals/$PRO/time-off?orderBy=reason" "" -H "$STAFF"
status_is 400 "time off: an order field not allowed"
req GET "/professionals/$PRO2/time-off" "" -H "$STAFF"
body_has '"total":0,' "time off: another professional has none"
req GET "/professionals/nothing/time-off" "" -H "$STAFF"
status_is 404 "time off: list for an unknown professional"

req GET "/professionals/$PRO/time-off/$XMAS" "" -H "$STAFF"
status_is 200 "time off: one"
req GET "/professionals/$PRO2/time-off/$XMAS" "" -H "$STAFF"
status_is 404 "time off: only through its own professional"
req GET "/professionals/$PRO/time-off/$XMAS" "" -H "$OTHER"
status_is 404 "time off: other tenant can't read demo's"
req GET "/professionals/$PRO/time-off" "" -H "$OTHER"
status_is 404 "time off: other tenant can't list demo's"
req DELETE "/professionals/$PRO/time-off/$XMAS" "" -H "$OTHER"
status_is 404 "time off: other tenant can't delete demo's"
req DELETE "/professionals/$PRO2/time-off/$XMAS" "" -H "$OWNER"
status_is 404 "time off: delete through another professional"

req DELETE "/professionals/$PRO/time-off/$OVERLAP" "" -H "$STAFF"
status_is 403 "time off: staff can't delete"
req DELETE "/professionals/$PRO/time-off/$OVERLAP" "" -H "$OWNER"
status_is 204 "time off: delete"
req DELETE "/professionals/$PRO/time-off/$OVERLAP" "" -H "$OWNER"
status_is 404 "time off: delete again"

# The schedule goes with its professional
req DELETE "/professionals/$PRO" "" -H "$OWNER"
status_is 204 "schedule: the professional deleted"
req GET "/professionals/$PRO/working-hours" "" -H "$OWNER"
status_is 404 "schedule: no week for a deleted professional"
req GET "/professionals/$PRO/time-off/$XMAS" "" -H "$OWNER"
status_is 404 "schedule: no time off for a deleted professional"
